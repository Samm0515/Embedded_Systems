// Initialize the filter's state
void init_filter(RollingAverageFilter* filter) {
    memset(filter->buffer, 0, sizeof(filter->buffer));
    filter->sum = 0.0f;
    filter->head = 0;
    filter->count = 0;
}

// Update the filter with a new value and return the new average
float update_filter(RollingAverageFilter* filter, float new_value) {
    if (filter->count < BUFFER_SIZE) {
        filter->count++;
    } else {
        filter->sum -= filter->buffer[filter->head];
    }

    filter->buffer[filter->head] = new_value;
    filter->sum += new_value;

    filter->head = (filter->head + 1) % BUFFER_SIZE;

    return filter->sum / filter->count;
}

